import * as THREE from 'three';

const LIMIT = 32;
const ACTIVE = new Set(['working', 'running', 'building', 'testing', 'researching', 'editing', 'reviewing', 'traveling']);
const SETTLED = new Set(['failed', 'passed', 'cancelled', 'interrupted', 'timed_out', 'stopping', 'termination_unknown']);
const finite = value => typeof value === 'number' && Number.isFinite(value);

// Capture the completed, neutral host graph after its antenna and rocket
// attachments exist. The source keeps ownership of every geometry/material.
// Positions and travel routes remain the caller's presentation of real state.
export function createRobotCrew({ template, scale = .65 } = {}) {
  if (!template?.isObject3D) throw new TypeError('Robot crew requires the original host template');
  if (!finite(scale) || scale <= 0) throw new RangeError('Robot crew scale must be positive and finite');
  template.updateWorldMatrix(true, true);
  if (Math.abs(template.matrixWorld.determinant()) < 1e-12) throw new RangeError('Robot template transform must be invertible');

  const root = new THREE.Group();
  root.name = 'OriginalHostRobotCrew';
  const inverse = template.matrixWorld.clone().invert();
  const parts = [], omitted = [];
  template.traverse(source => {
    if (!source.isMesh) return;
    if (source.isSkinnedMesh || source.isInstancedMesh) throw new TypeError('Robot template must contain ordinary rigid host meshes');
    let visible = true;
    for (let parent = source; parent && parent !== template; parent = parent.parent) visible &&= parent.visible;
    if (!visible) return;
    const materials = Array.isArray(source.material) ? source.material : [source.material];
    // The source exhaust shader writes world coordinates without instanceMatrix.
    // Keep its original rigid rocket hardware, but never draw misplaced flames
    // or modify a shared source shader to manufacture per-worker effects.
    if (materials.some(material => material?.isShaderMaterial && !/\binstanceMatrix\b/.test(material.vertexShader || ''))) {
      omitted.push(source.name || 'Non-instanced transient shader');
      return;
    }
    const mesh = new THREE.InstancedMesh(source.geometry, source.material, LIMIT);
    mesh.name = `Crew:${source.name || source.uuid}`;
    mesh.count = 0;
    mesh.castShadow = source.castShadow;
    mesh.receiveShadow = source.receiveShadow;
    mesh.renderOrder = source.renderOrder;
    mesh.layers.mask = source.layers.mask;
    // Small bounded crew; avoid stale instance bounds after caller-driven travel.
    mesh.frustumCulled = false;
    mesh.instanceMatrix.setUsage(THREE.DynamicDrawUsage);
    root.add(mesh);
    parts.push({ mesh, local: inverse.clone().multiply(source.matrixWorld) });
  });
  if (!parts.length) throw new TypeError('Robot template has no renderable rigid meshes');
  root.userData.crew = { limit: LIMIT, scale, meshBatches: parts.length, omittedTransientMeshes: omitted, records: [] };

  let records = [], disposed = false, lastTime = 0, lastReduced = false;
  const matrix = new THREE.Matrix4(), actor = new THREE.Matrix4();
  const position = new THREE.Vector3(), rotation = new THREE.Quaternion(), up = new THREE.Vector3(0, 1, 0), size = new THREE.Vector3(scale, scale, scale);

  function update(time = 0, reduced = false) {
    if (disposed) return;
    lastTime = finite(time) ? time : 0;
    lastReduced = !!reduced;
    let count = 0;
    const metadata = [];
    for (let index = 0; index < records.length; index++) {
      const record = records[index], point = record?.position;
      const x = point?.x ?? point?.[0], y = point?.y ?? point?.[1], z = point?.z ?? point?.[2];
      if (![x, y, z].every(finite)) continue;
      const scenery = record.scenery === true;
      const moving = record.motionAllowed !== false && !record.stale && !record.terminal && !SETTLED.has(record.state) && (scenery || ACTIVE.has(record.state));
      // Only a tiny hover is authored here. No simulated task progress, route,
      // color, completion or result can be generated by a presentation timer.
      const hover = moving && !lastReduced ? Math.sin(lastTime * 1.8 + index * 1.7) * .035 : 0;
      position.set(x, y + hover, z);
      rotation.setFromAxisAngle(up, finite(record.heading) ? record.heading : 0);
      actor.compose(position, rotation, size);
      for (const part of parts) {
        matrix.multiplyMatrices(actor, part.local);
        part.mesh.setMatrixAt(count, matrix);
      }
      metadata.push({ id: record.id ?? record.workerId ?? null, scenery, state: record.state || 'idle', motionAllowed: moving });
      count++;
    }
    for (const part of parts) { part.mesh.count = count; part.mesh.instanceMatrix.needsUpdate = true; }
    root.userData.crew.records = metadata;
  }

  function set(values = []) {
    if (disposed) return;
    if (!Array.isArray(values)) throw new TypeError('Robot crew records must be an array');
    // Retain record references so an owning route can update positions without
    // re-creating the crew. Never mutate those caller-owned records.
    records = values.slice(0, LIMIT);
    update(lastTime, lastReduced);
  }

  function dispose() {
    if (disposed) return;
    disposed = true;
    records = [];
    root.removeFromParent();
    for (const part of parts) {
      part.mesh.count = 0;
      part.mesh.removeFromParent();
      part.mesh.dispose(); // Instance-owned buffers only; not source resources.
    }
    parts.length = 0;
    root.userData.crew.records = [];
  }
  return { root, set, update, dispose };
}
